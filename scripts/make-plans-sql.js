// Generates the Supabase migration for the carriers / carrier_plans tables from data/plans.demo.json,
// so the SQL and the offline copy of the data can never drift apart.
//   node scripts/make-plans-sql.js
const fs = require("fs");
const path = require("path");

const data = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "data", "plans.demo.json"), "utf8"));
const OUT = path.join(__dirname, "..", "supabase", "migrations", "20261018000000_carrier_plans.sql");

const q = (v) => v === null || v === undefined ? "null" : typeof v === "boolean" ? String(v) : typeof v === "number" ? String(v) : "'" + String(v).replace(/'/g, "''") + "'";
const arr = (a) => "array[" + a.map(q).join(", ") + "]::text[]";

const header = `-- Competitor and own-plan facts the coaching agent compares against.
-- GENERATED by scripts/make-plans-sql.js from data/plans.demo.json. Edit the JSON and regenerate; do not hand-edit.
-- All rows below are FICTIONAL demo data (is_demo = true). Real data must carry a real source and verified_on date.
--
-- Run this once in the Supabase dashboard (SQL Editor), or with \`supabase db push\`.

create table if not exists public.carriers (
  id text primary key,
  name text not null,
  aliases text[] not null default '{}',   -- lowercase words a customer might say for this carrier
  is_us boolean not null default false,   -- true for our own carrier
  is_demo boolean not null default false
);

create table if not exists public.carrier_plans (
  id text primary key,
  carrier_id text not null references public.carriers(id) on delete cascade,
  name text not null,
  price_per_line numeric(8,2),            -- per-line plans
  bundle_lines integer,                   -- fixed bundles, e.g. 3 lines ...
  bundle_price numeric(8,2),              -- ... for $120 total
  regular_price_per_line numeric(8,2),    -- price after an intro period (null = same as above)
  promo_months integer,                   -- how long the intro price lasts
  data_policy text,
  includes text[] not null default '{}',  -- perks that come with the plan
  price_lock_years integer,
  contract_months integer,
  taxes_fees_included boolean,            -- null = not known; the agent must then say it will confirm
  hotspot_note text,
  promo_note text,
  promo_ends date,
  source_url text,
  verified_on date not null,              -- when someone last checked this against the carrier; the agent flags old rows
  active boolean not null default true,
  is_demo boolean not null default false,
  created_at timestamptz not null default timezone('utc', now()),
  constraint plan_has_a_price check (price_per_line is not null or (bundle_lines is not null and bundle_price is not null))
);

create index if not exists carrier_plans_carrier_idx on public.carrier_plans (carrier_id);

-- Same access model as the rest of this project: the publishable key can only READ demo rows.
alter table public.carriers enable row level security;
alter table public.carrier_plans enable row level security;
drop policy if exists carriers_public_demo_read on public.carriers;
drop policy if exists carrier_plans_public_demo_read on public.carrier_plans;
create policy carriers_public_demo_read on public.carriers for select to anon, authenticated using (is_demo);
create policy carrier_plans_public_demo_read on public.carrier_plans for select to anon, authenticated using (is_demo and active);
grant select on public.carriers, public.carrier_plans to anon, authenticated;
grant all on public.carriers, public.carrier_plans to service_role;

`;

const carriers = data.carriers.map((c) =>
  `  (${q(c.id)}, ${q(c.name)}, ${arr(c.aliases)}, ${q(c.is_us)}, ${q(c.is_demo)})`).join(",\n");
const cols = ["id", "carrier_id", "name", "price_per_line", "bundle_lines", "bundle_price", "regular_price_per_line", "promo_months",
  "data_policy", "includes", "price_lock_years", "contract_months", "taxes_fees_included", "hotspot_note", "promo_note", "promo_ends",
  "source_url", "verified_on", "active", "is_demo"];
const plans = data.plans.map((p) => "  (" + cols.map((c) => c === "includes" ? arr(p.includes) : q(p[c])).join(", ") + ")").join(",\n");
const setCols = cols.filter((c) => c !== "id").map((c) => `${c} = excluded.${c}`).join(", ");

const sql = header +
  `insert into public.carriers (id, name, aliases, is_us, is_demo) values\n${carriers}\non conflict (id) do update set name = excluded.name, aliases = excluded.aliases, is_us = excluded.is_us, is_demo = excluded.is_demo;\n\n` +
  `insert into public.carrier_plans (${cols.join(", ")}) values\n${plans}\non conflict (id) do update set ${setCols};\n`;
fs.writeFileSync(OUT, sql);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${data.carriers.length} carriers, ${data.plans.length} plans`);
